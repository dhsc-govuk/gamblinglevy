// Static transcription of the Question Protocol's "Results table" sheet ("Question Protocol Cross
// Reference-Updated - 3 July.xlsx", BLUM-6933; originally "MASTER Question protocol - LA user.xlsx", BLUM-6611) —
// the per-activity-type standard key results and the quarterly-report questions they unlock.
//
// Conventions:
// - One ProtocolTypeSeed per activity type, keyed by the SEEDED ActivityTask name (the taxonomy is aligned to the
//   protocol by SeedActivityReferenceData + the BLUM_6611_AlignActivityTaskTaxonomy migration).
// - Key-result codes are per-type snake_case; question codes are UPPER_SNAKE. The Active and Closed/Finished
//   phrasing variants of one underlying question are separate rows sharing a Code, differing by StatusScope —
//   saved answers key on Code so they survive an activity status change.
// - "n/a" status variants in the sheet are simply not seeded. The "[X] Other" rows are not seeded either: custom
//   (KeyResultCode == null) ActivityExpectedResult rows get a generic progress question synthesised by the
//   resolver, as do the four "Other type of …" activity types and People-and-roles (no entries here at all).
// - Boolean questions carry no options — the resolver synthesises yes/no radio options.
// - ErrorMessage is the sheet's empty-on-submit message verbatim; numeric type/range messages are generated by the
//   validator from FieldType + Min/Max. A handful of sheet rows have misaligned columns or copy-paste errors —
//   each judgment call is flagged with a "Sheet:" comment.
